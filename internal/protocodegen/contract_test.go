// repoRoot is the repository root relative to this package's directory, so the
// tests read the working tree wherever "go test" is invoked from. It follows
// the convention internal/speccoverage uses.
const repoRoot = "../.."

// modulePath is the module prefix every contract's go_package must be rooted
// at for client and server code to import the generated Go at the path the
// contract promises.
const modulePath = "github.com/DisMosGit/fleetops"

// The declarations these tests read out of a contract. Parsing the contract
// source, not the generated output, is what lets the layout assertions fail on
// the file that broke the rule.
var (
	protoPkgRE      = regexp.MustCompile(`(?m)^\s*package\s+([A-Za-z_][\w.]*)\s*;`)
	goPackageRE     = regexp.MustCompile(`(?m)^\s*option\s+go_package\s*=\s*"([^";]+)(?:;([\w.]+))?"\s*;`)
	protoImportRE   = regexp.MustCompile(`(?m)^\s*import\s+(?:public\s+|weak\s+)?"([^"]+)"\s*;`)
	protoServiceRE  = regexp.MustCompile(`(?m)^\s*service\s+([A-Za-z_]\w*)\s*\{`)
	packageClauseRE = regexp.MustCompile(`(?m)^package\s+([A-Za-z_]\w*)`)
)

// protoFile is the layout-relevant subset of one .proto contract.
type protoFile struct {
	path      string   // repository-relative, slash-separated
	protoPkg  string   // the `package` statement, e.g. fleetops.agent.v1
	goPkg     string   // the import path from `option go_package`
	goPkgName string   // the Go package name from `option go_package`, after the ";"
	imports   []string // every imported contract path, in source order
	services  []string // every declared service
}

// parseContract extracts the declarations the layout rules constrain. A
// contract without go_package cannot map its Go to the required import path,
// so that is an error rather than an empty field.
func parseContract(file string, src []byte) (protoFile, error) {
	out := protoFile{path: file}

	m := protoPkgRE.FindSubmatch(src)
	if m == nil {
		return protoFile{}, fmt.Errorf("%s: no package statement", file)
	}
	out.protoPkg = string(m[1])

	m = goPackageRE.FindSubmatch(src)
	if m == nil {
		return protoFile{}, fmt.Errorf("%s: no option go_package", file)
	}
	out.goPkg = string(m[1])
	if len(m[2]) > 0 {
		out.goPkgName = string(m[2])
	} else {
		// protoc derives the Go package name from the last path element when
		// go_package carries no explicit name.
		out.goPkgName = path.Base(out.goPkg)
	}

	for _, im := range protoImportRE.FindAllSubmatch(src, -1) {
		out.imports = append(out.imports, string(im[1]))
	}
	for _, sv := range protoServiceRE.FindAllSubmatch(src, -1) {
		out.services = append(out.services, string(sv[1]))
	}
	return out, nil
}

// loadContracts reads every contract under api/proto in path order.
func loadContracts(t *testing.T, fsys fs.FS) []protoFile {
	t.Helper()

	var paths []string
	err := fs.WalkDir(fsys, "api/proto", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(p, ".proto") {
			paths = append(paths, p)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk api/proto: %v", err)
	}
	if len(paths) == 0 {
		t.Fatal("no contracts found under api/proto")
	}
	sort.Strings(paths)

	out := make([]protoFile, 0, len(paths))
	for _, p := range paths {
		src, err := fs.ReadFile(fsys, p)
		if err != nil {
			t.Fatalf("read %s: %v", p, err)
		}
		contract, err := parseContract(p, src)
		if err != nil {
			t.Fatalf("parse contract: %v", err)
		}
		out = append(out, contract)
	}
	return out
}

// contractContext returns the bounded context of a contract at
// api/proto/<context>/v1/<file>.proto and reports whether the path has that
// shape, which is the layout the capability fixes.
func contractContext(file string) (string, bool) {
	parts := strings.Split(file, "/")
	if len(parts) != 5 || parts[0] != "api" || parts[1] != "proto" || parts[3] != "v1" {
		return "", false
	}
	return parts[2], true
}

// stub is one generated file that must sit beside its contract.
type stub struct {
	path   string // repository-relative
	header string // the generator's do-not-edit line
}

// stubsFor returns the generated files a contract must have beside it: always
// the message stub, plus the gRPC stub when the contract declares a service.
func stubsFor(c protoFile) []stub {
	stem := strings.TrimSuffix(path.Base(c.path), ".proto")
	dir := path.Dir(c.path)
	out := []stub{{
		path:   path.Join(dir, stem+".pb.go"),
		header: "// Code generated by protoc-gen-go. DO NOT EDIT.",
	}}
	if len(c.services) > 0 {
		out = append(out, stub{
			path:   path.Join(dir, stem+"_grpc.pb.go"),
			header: "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.",
		})
	}
	return out
}

// findStubs returns every committed generated Go stub under api/proto.
func findStubs(t *testing.T, fsys fs.FS) []string {
	t.Helper()

	var stubs []string
	err := fs.WalkDir(fsys, "api/proto", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(p, ".pb.go") {
			stubs = append(stubs, p)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk api/proto: %v", err)
	}
	if len(stubs) == 0 {
		t.Fatal("no generated stubs under api/proto")
	}
	sort.Strings(stubs)
	return stubs
}

// packageClause returns the package name a generated file declares.
func packageClause(src string) string {
	m := packageClauseRE.FindStringSubmatch(src)
	if m == nil {
		return ""
	}
	return m[1]
}

// importsPackage reports whether a non-test Go file under dir imports pkg. Test
// files are skipped: the scenario is about client and server code, and a test's
// import would not make the generated package part of a shipped surface.
func importsPackage(t *testing.T, fsys fs.FS, dir, pkg string) bool {
	t.Helper()

	found := false
	err := fs.WalkDir(fsys, dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
			return nil
		}
		src, err := fs.ReadFile(fsys, p)
		if err != nil {
			return err
		}
		file, err := parser.ParseFile(token.NewFileSet(), p, src, parser.ImportsOnly)
		if err != nil {
			return fmt.Errorf("parse %s: %w", p, err)
		}
		for _, spec := range file.Imports {
			if strings.Trim(spec.Path.Value, `"`) == pkg {
				found = true
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("scan %s for imports of %s: %v", dir, pkg, err)
	}
	return found
}

// foreignContractImport reports the context an import reaches into when it is
// neither a well-known type nor part of the importer's own context. A bounded
// context owns its messages, so any other contract import breaks independence.
func foreignContractImport(context, imp string) (string, bool) {
	if strings.HasPrefix(imp, "google/protobuf/") {
		return "", false
	}
	owner, _, _ := strings.Cut(imp, "/")
	if owner == context {
		return "", false
	}
	return owner, true
}

// sortedKeys returns a map's keys in sorted order, so failures are reported in
// a stable order.
func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// TestContractLayout backs "Predictable import path": the agent contract (and
// every other contract) maps its Go to <module>/api/proto/<context>/v1, the
// generated stubs sit beside it under that package name, and client and server
// packages import that exact path. Renaming the option, moving the contract, or
// dropping a stub fails on the offending file.
func TestContractLayout(t *testing.T) {
	t.Parallel()

	fsys := os.DirFS(repoRoot)
	contracts := loadContracts(t, fsys)

	byContext := make(map[string][]protoFile)
	for _, c := range contracts {
		context, ok := contractContext(c.path)
		if !ok {
			t.Errorf("%s: contract must live at api/proto/<context>/v1/<file>.proto", c.path)
			continue
		}
		byContext[context] = append(byContext[context], c)
	}
	if len(byContext) == 0 {
		t.Fatal("no contract matches the api/proto/<context>/v1/ layout")
	}

	// The client and server packages that must import each context's generated
	// Go at the path its contract promises. A context missing here fails the
	// check below, so a new context has to name its consumers.
	wantConsumers := map[string][]string{
		"agent":   {"internal/agent", "internal/agentserver"},
		"rollout": {"internal/wavehealth", "cmd/controlplane"},
	}
	for _, context := range sortedKeys(wantConsumers) {
		if _, ok := byContext[context]; !ok {
			t.Errorf("no contract found for context %s; the walker or the contract layout lost it", context)
		}
	}

	for _, context := range sortedKeys(byContext) {
		t.Run(context, func(t *testing.T) {
			wantGoPkg := modulePath + "/api/proto/" + context + "/v1"
			wantProtoPkg := "fleetops." + context + ".v1"

			for _, c := range byContext[context] {
				if c.goPkg != wantGoPkg {
					t.Errorf("%s: option go_package is %q, want %q so both sides of the wire import the generated Go at the contract's path", c.path, c.goPkg, wantGoPkg)
				}
				if c.protoPkg != wantProtoPkg {
					t.Errorf("%s: proto package is %q, want %q so one bounded context owns one proto package", c.path, c.protoPkg, wantProtoPkg)
				}
				assertStubsBeside(t, fsys, c)
			}

			dirs, ok := wantConsumers[context]
			if !ok {
				t.Fatalf("no consuming packages recorded for context %s; name the client and server packages that import %s", context, wantGoPkg)
			}
			for _, dir := range dirs {
				if !importsPackage(t, fsys, dir, wantGoPkg) {
					t.Errorf("%s: no non-test Go file imports %s; the generated Go must be reachable at the path the contract promises", dir, wantGoPkg)
				}
			}
		})
	}
}

// assertStubsBeside fails when a contract's generated files are missing, do not
// sit beside it, do not carry the generator's do-not-edit header, or declare a
// package other than the one go_package names.
func assertStubsBeside(t *testing.T, fsys fs.FS, c protoFile) {
	t.Helper()

	for _, s := range stubsFor(c) {
		src, err := fs.ReadFile(fsys, s.path)
		if err != nil {
			t.Errorf("%s: generated stub for %s is not beside it: %v", s.path, c.path, err)
			continue
		}
		text := string(src)
		if !strings.Contains(text, s.header) {
			t.Errorf("%s: missing %q; generated files are build artifacts that name their generator", s.path, s.header)
		}
		if got := packageClause(text); got != c.goPkgName {
			t.Errorf("%s: package %q, want %q from %s's go_package", s.path, got, c.goPkgName, c.path)
		}
	}
}

// TestStubsLiveOnlyUnderProto backs the layout requirement's "no generated Go
// package lives outside api/proto": every committed stub sits beside the
// contract that produced it, and no *.pb.go appears anywhere else in the
// module.
func TestStubsLiveOnlyUnderProto(t *testing.T) {
	t.Parallel()

	fsys := os.DirFS(repoRoot)
	var stubs []string
	err := fs.WalkDir(fsys, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if p == ".git" || p == "node_modules" {
				return fs.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(p, ".pb.go") {
			stubs = append(stubs, p)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", repoRoot, err)
	}
	if len(stubs) == 0 {
		t.Fatal("found no *.pb.go; the generated stubs are gone or moved out of the walk")
	}

	var strays []string
	for _, p := range stubs {
		if !strings.HasPrefix(p, "api/proto/") {
			strays = append(strays, p)
			continue
		}
		// agent/v1/agent.pb.go and agent/v1/agent_grpc.pb.go both come from
		// agent/v1/agent.proto.
		stem := strings.TrimSuffix(strings.TrimSuffix(path.Base(p), ".pb.go"), "_grpc")
		contract := path.Join(path.Dir(p), stem+".proto")
		if _, err := fs.Stat(fsys, contract); err != nil {
			t.Errorf("%s: no %s beside it; generated files are written beside the contract that produced them", p, contract)
		}
	}
	if diff := cmp.Diff([]string(nil), strays); diff != "" {
		t.Errorf("generated Go outside api/proto (-want +got):\n%s", diff)
	}
}
